import Foundation

/// A logbook (09 §2): one per book; `type` is airframe, engine, prop, avionics or other.
struct LogbookRow: Decodable, Equatable, Sendable, Identifiable {
    let id: String
    let type: String
    let title: String?
}

/// A scanned page (the columns the Logbooks screens read).
struct PageRow: Decodable, Equatable, Sendable, Identifiable {
    let id: String
    let logbook_id: String
    let page_sequence: Int?
    /// "unreviewed", "confirmed" or "disputed".
    var review_status: String
    /// "queued", "processing", "waiting_allowance", "extracted", "failed" …
    let extraction_status: String
    let landing_date: String?
    let needs_look: Bool?
    let unread_rotated_content: Bool?
    var updated_at: String
}

/// Where a field's ink sits on the page image, as fractions 0…1 from the top left (09; extraction schema).
struct FieldBox: Codable, Equatable, Sendable {
    let x, y, w, h: Double
}

/// One log entry with what the reader made of it (log_entry, 09 §2).
struct EntryRow: Decodable, Equatable, Sendable, Identifiable {
    let id: String
    let page_id: String?
    let logbook_id: String
    var entry_date: String?
    var tach: Double?
    var hobbs: Double?
    var description: String?
    var work_performed: String?
    var signature_name: String?
    var mechanic_cert_number: String?
    let ad_refs: [String]?
    let confidence: Double?
    let field_confidence: [String: Double]?
    let field_boxes: [String: FieldBox?]?
    var owner_confirmed: Bool
    let is_continuation: Bool?
    let entry_index: Int?
    /// "ai_read", "confirmed" or "signed" (generated by the database).
    var trust: String
    var updated_at: String
}

/// GET /api/aircraft/{id}/gaps/{gapId}/evidence (09 §3.8, §4.7): what the other books show, from confirmed entries only.
struct GapEvidence: Decodable, Equatable, Sendable {
    struct Gap: Decodable, Equatable, Sendable {
        let id: String; let logbook: String; let from: String; let to: String; let status: String; let note: String?
    }
    struct Book: Decodable, Equatable, Sendable {
        let logbook: String; let entries: Int; let annuals: Int; let tachFrom: Double?; let tachTo: Double?; let pageRange: String?
    }
    struct Neighbour: Decodable, Equatable, Sendable { let pageId: String; let label: String; let entryId: String? }
    struct Neighbours: Decodable, Equatable, Sendable { let before: Neighbour?; let after: Neighbour? }
    let gap: Gap
    let otherBooks: [Book]
    let hoursFlownApprox: Double?
    let unconfirmedPagesInGap: Int
    let verdict: String
    let neighbourPages: Neighbours?
}

/// A JSON value for mutation payloads.
enum JSONValue: Encodable, Equatable, Sendable {
    case string(String), number(Double), bool(Bool), null

    func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        switch self {
        case .string(let s): try c.encode(s)
        case .number(let n): try c.encode(n)
        case .bool(let b): try c.encode(b)
        case .null: try c.encodeNil()
        }
    }
}

/// One queued write (09 §5, apps/web/src/lib/sync/mutations.ts). `base` is the row's updated_at for writes that change one.
struct Mutation: Encodable, Equatable, Sendable {
    var id = UUID().uuidString.lowercased()
    let type: String
    let aircraftId: String
    let payload: [String: PayloadValue]
    let base: String?

    /// Payload values: scalars, or `fields` for entry.update.
    enum PayloadValue: Encodable, Equatable, Sendable {
        case value(JSONValue)
        case object([String: JSONValue])
        func encode(to encoder: Encoder) throws {
            switch self {
            case .value(let v): try v.encode(to: encoder)
            case .object(let o): try o.encode(to: encoder)
            }
        }
    }
}

/// POST /api/sync/push answers one result per mutation, in order.
struct PushResult: Decodable, Equatable, Sendable {
    let id: String
    /// "ok", "conflict" or "error".
    let status: String
    let error: String?
    /// The row as written; its updated_at is the base for the next write to it (Undo).
    let row: Stamp?

    struct Stamp: Decodable, Equatable, Sendable { let updated_at: String? }
}

/// Logbooks reads (map, evidence, pages, entries) and the writes it sends through the push endpoint, as the signed-in
/// user under RLS. Viewers read everything; the server refuses their writes.
/// shortcut: online only until the phase 3 mirror and outbox; writes go straight to push instead of a queue.
extension StatusAPI {
    func map(token: String, aircraftId: String) async throws -> MapData {
        try await get(apiURL.appending(path: "api/aircraft/\(aircraftId)/map"), token, apiKey: false)
    }

    func gapEvidence(token: String, aircraftId: String, gapId: String) async throws -> GapEvidence {
        try await get(apiURL.appending(path: "api/aircraft/\(aircraftId)/gaps/\(gapId)/evidence"), token, apiKey: false)
    }

    func logbooks(token: String, aircraftId: String) async throws -> [LogbookRow] {
        try await get(rest("logbook", ["select": "id,type,title", "aircraft_id": "eq.\(aircraftId)"]), token)
    }

    func pages(token: String, aircraftId: String) async throws -> [PageRow] {
        try await get(rest("page", [
            "select": "id,logbook_id,page_sequence,review_status,extraction_status,landing_date,needs_look,unread_rotated_content,updated_at",
            "aircraft_id": "eq.\(aircraftId)", "order": "page_sequence.asc.nullslast",
        ]), token)
    }

    /// shortcut: one read of every entry (PostgREST caps it at 1,000 rows); page through when an aircraft passes that.
    func entries(token: String, aircraftId: String) async throws -> [EntryRow] {
        try await get(rest("log_entry", [
            "select": "id,page_id,logbook_id,entry_date,tach,hobbs,description,work_performed,signature_name,mechanic_cert_number,ad_refs,confidence,field_confidence,field_boxes,owner_confirmed,is_continuation,entry_index,trust,updated_at",
            "aircraft_id": "eq.\(aircraftId)", "replaced_by_entry_id": "is.null", "order": "entry_date.asc.nullslast",
        ]), token)
    }

    /// A page image through the app (thumbnail when `thumb`), cached by URLSession.
    func pageImage(token: String, pageId: String, thumb: Bool, version: String) async throws -> Data {
        var url = apiURL.appending(path: "api/page/\(pageId)/image")
        url.append(queryItems: (thumb ? [URLQueryItem(name: "thumb", value: "1")] : []) + [URLQueryItem(name: "v", value: version)])
        var request = URLRequest(url: url, timeoutInterval: 30)
        request.setValue("Bearer \(token)", forHTTPHeaderField: "Authorization")
        let (data, response) = try await http.data(for: request)
        let status = (response as? HTTPURLResponse)?.statusCode ?? 0
        guard (200..<300).contains(status) else { throw HTTPError(status: status) }
        return data
    }

    func push(token: String, _ mutations: [Mutation]) async throws -> [PushResult] {
        struct Body: Encodable { let mutations: [Mutation] }
        struct Answer: Decodable { let results: [PushResult] }
        var request = URLRequest(url: apiURL.appending(path: "api/sync/push"), timeoutInterval: 30)
        request.httpMethod = "POST"
        request.setValue("Bearer \(token)", forHTTPHeaderField: "Authorization")
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        request.httpBody = try JSONEncoder().encode(Body(mutations: mutations))
        let (data, response) = try await http.data(for: request)
        let status = (response as? HTTPURLResponse)?.statusCode ?? 0
        guard (200..<300).contains(status) else { throw HTTPError(status: status) }
        return try JSONDecoder().decode(Answer.self, from: data).results
    }
}
