#!/usr/bin/env node
// Generates platform token files from packages/shared/tokens/tokens.json (13 §5 phase 0).
//   node packages/shared/scripts/build-tokens.mjs           write the files
//   node packages/shared/scripts/build-tokens.mjs --check   fail if any file is stale (CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const SRC = join(ROOT, "packages/shared/tokens/tokens.json");
const OUT = {
  css: join(ROOT, "apps/web/src/ui/tokens.css"),
  swift: join(ROOT, "apps/ios/MyTailLog/DesignSystem/Tokens.swift"),
  kotlin: join(ROOT, "apps/android/core-design/src/main/kotlin/com/mytaillog/design/Tokens.kt"),
};
const DARK = "com.mytaillog.dark";
const HEADER = "Generated by packages/shared/scripts/build-tokens.mjs from packages/shared/tokens/tokens.json. Do not edit.";

/** Flatten to [{ path: ['color','section','status'], type, value, dark }]. */
export function flatten(node, path = [], inheritedType) {
  const type = node.$type ?? inheritedType;
  if ("$value" in node) return [{ path, type, value: node.$value, dark: node.$extensions?.[DARK] }];
  return Object.entries(node)
    .filter(([k]) => !k.startsWith("$"))
    .flatMap(([k, v]) => flatten(v, [...path, k], type));
}

const kebab = (path) => path.join("-");
export const camel = (path) =>
  path
    .join("-")
    .split("-")
    .map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1)))
    .join("");

/** "#rrggbb" or "rgba(r,g,b,a)" → [r,g,b,a] with a in 0..1. */
export function rgba(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) {
    const n = parseInt(hex[1], 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255, 1];
  }
  const m = /^rgba?\(([^)]+)\)$/.exec(value.replace(/\s/g, ""));
  if (!m) throw new Error(`Unparseable colour ${value}`);
  const [r, g, b, a = "1"] = m[1].split(",");
  return [Number(r), Number(g), Number(b), Number(a)];
}

const px = (v) => parseFloat(String(v));
const ref = (v) => (typeof v === "string" ? v.replace(/^\{font\.(\w+)\}$/, "var(--font-$1)") : v);

// ---------------------------------------------------------------- web CSS
function buildCss(tokens) {
  const colors = tokens.filter((t) => t.type === "color");
  const light = colors.map((t) => `  --${kebab(t.path)}: ${t.value};`);
  const dark = colors.filter((t) => t.dark).map((t) => `  --${kebab(t.path)}: ${t.dark};`);
  const other = [];
  const theme = [];
  for (const t of tokens) {
    const [group, ...rest] = t.path;
    const name = rest.join("-");
    if (group === "font" && t.type === "fontFamily") {
      const loaded = name === "app" ? "--font-libre-franklin" : "--font-literata";
      const stack = t.value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
      other.push(`  --font-${name}: var(${loaded}, "${t.value[0]}"), ${stack};`);
      theme.push(`  --font-${name}: var(--font-${name});`);
    } else if (group === "type" && rest[0] === "web") {
      const role = rest.slice(1).join("-");
      const v = t.value;
      other.push(
        `  --type-${role}-size: ${v.fontSize};`,
        `  --type-${role}-weight: ${v.fontWeight};`,
        `  --type-${role}-lh: ${v.lineHeight ?? "normal"};`,
        `  --type-${role}-ls: ${v.letterSpacing ?? "normal"};`,
      );
      theme.push(
        `  --text-${role}: var(--type-${role}-size);`,
        `  --text-${role}--line-height: var(--type-${role}-lh);`,
        `  --text-${role}--font-weight: var(--type-${role}-weight);`,
        `  --text-${role}--letter-spacing: var(--type-${role}-ls);`,
      );
    } else if (group === "elevation") {
      const v = t.value;
      other.push(`  --shadow-${name}: ${v.offsetX} ${v.offsetY} ${v.blur} ${v.spread} ${v.color};`);
      theme.push(`  --shadow-${name}: var(--shadow-${name});`);
    } else if (group === "motion") {
      const v = Array.isArray(t.value) ? `cubic-bezier(${t.value.join(", ")})` : t.value;
      other.push(`  --motion-${name}: ${v};`);
    } else if (group === "border") {
      other.push(`  --border-${name}: ${t.value.width} ${t.value.style} ${ref(t.value.color).replace(/^\{color\.(.+)\}$/, (_, p) => `var(--color-${p.replace(/\./g, "-")})`)};`);
    } else if (["space", "radius", "size", "map"].includes(group)) {
      const unitless = group === "map" || /^phone-/.test(name);
      other.push(`  --${group}-${name}: ${t.value}${unitless && /^[\d.]+$/.test(t.value) ? "px" : ""};`);
    } else if (group === "font") {
      other.push(`  --font-${name}: "${t.value}";`);
    }
  }
  // Tailwind utilities for the v2 vocabulary. Values resolve at the element, so the [data-ui] scope and
  // [data-section] boards below decide them; v1 keeps its own --color-ink etc. outside the scope.
  // `ink` is already a v1 Tailwind colour (`--color-ink: var(--ink)`); the v2 scope overrides --color-ink itself.
  const V1_NAMES = new Set(["ink"]);
  for (const t of colors) {
    if (!V1_NAMES.has(kebab(t.path.slice(1)))) theme.push(`  --color-${kebab(t.path.slice(1))}: var(--${kebab(t.path)});`);
  }
  theme.push(
    "  --color-board: var(--board);",
    "  --color-on-board: var(--on-board);",
    "  --color-on-board-2: var(--on-board-2);",
    "  --color-board-ink: var(--board-ink);",
    // radius.s/m/l would collide with Tailwind's logical rounded-s; aliased by use.
    "  --radius-leaf: var(--radius-s);",
    "  --radius-control: var(--radius-m);",
    "  --radius-tab: var(--radius-l);",
  );
  const sections = Object.keys(tokens.find((t) => t.path[1] === "section")
    ? Object.fromEntries(tokens.filter((t) => t.path[1] === "section").map((t) => [t.path[2], 1]))
    : {});
  const boards = sections.map(
    (s) =>
      `[data-ui="v2"] [data-section="${s}"], [data-ui="v2"][data-section="${s}"] {\n` +
      `  --board: var(--color-section-${s});\n  --on-board: var(--color-on-section-${s});\n` +
      `  --on-board-2: var(--color-on-section-2-${s});\n  --board-ink: var(--color-section-ink-${s});\n}`,
  );
  return `/* ${HEADER} */

@theme inline {
${theme.join("\n")}
}

[data-ui="v2"] {
  color-scheme: light;
${light.join("\n")}
${other.join("\n")}
  --board: var(--color-section-setup);
  --on-board: var(--color-on-section-setup);
  --on-board-2: var(--color-on-section-2-setup);
  --board-ink: var(--color-section-ink-setup);
}

@media (prefers-color-scheme: dark) {
  [data-ui="v2"]:not([data-theme="light"]) {
    color-scheme: dark;
${dark.map((l) => "  " + l).join("\n")}
  }
}

[data-ui="v2"][data-theme="dark"] {
  color-scheme: dark;
${dark.join("\n")}
}

${boards.join("\n\n")}
`;
}

// ---------------------------------------------------------------- Swift
function buildSwift(tokens) {
  const swiftColor = (v) => {
    const [r, g, b, a] = rgba(v);
    return `RGBA(${r}, ${g}, ${b}, ${a})`;
  };
  const colors = tokens
    .filter((t) => t.type === "color")
    .map((t) => `        public static let ${camel(t.path.slice(1))} = Color.dynamic(light: ${swiftColor(t.value)}, dark: ${swiftColor(t.dark ?? t.value)})`);
  const dims = (group) =>
    tokens
      .filter((t) => t.path[0] === group && /^[\d.]+(px)?$/.test(String(t.value)))
      .map((t) => `        public static let ${camel(t.path.slice(1))}: CGFloat = ${px(t.value)}`);
  const phoneType = tokens
    .filter((t) => t.path[0] === "type" && t.path[1] === "phone")
    .map((t) => {
      const v = t.value;
      const family = v.fontFamily === "{font.paper}" ? ".paper" : ".app";
      return `        public static let ${camel(t.path.slice(2))} = TypeRole(family: ${family}, size: ${px(v.fontSize)}, weight: ${v.fontWeight}, lineHeight: ${v.lineHeight ?? 1.2})`;
    });
  const motion = tokens
    .filter((t) => t.path[0] === "motion" && t.type === "duration")
    .map((t) => `        public static let ${camel(t.path.slice(1))}: Double = ${px(t.value) / 1000}`);
  return `// ${HEADER}
import SwiftUI

public struct RGBA { let r, g, b: Double; let a: Double
    init(_ r: Double, _ g: Double, _ b: Double, _ a: Double) { self.r = r / 255; self.g = g / 255; self.b = b / 255; self.a = a } }

public extension Color {
    static func dynamic(light: RGBA, dark: RGBA) -> Color {
        Color(UIColor { $0.userInterfaceStyle == .dark
            ? UIColor(red: dark.r, green: dark.g, blue: dark.b, alpha: dark.a)
            : UIColor(red: light.r, green: light.g, blue: light.b, alpha: light.a) })
    }
}

public struct TypeRole { public enum Family { case app, paper }
    public let family: Family; public let size: CGFloat; public let weight: Int; public let lineHeight: CGFloat }

public enum Tokens {
    public enum Colors {
${colors.join("\n")}
    }
    public enum Space {
${dims("space").join("\n")}
    }
    public enum Radius {
${dims("radius").join("\n")}
    }
    public enum Size {
${dims("size").join("\n")}
    }
    public enum Map {
${dims("map").join("\n")}
    }
    public enum PhoneType {
${phoneType.join("\n")}
    }
    public enum Motion {
${motion.join("\n")}
    }
}
`;
}

// ---------------------------------------------------------------- Kotlin
function buildKotlin(tokens) {
  const argb = (v) => {
    const [r, g, b, a] = rgba(v);
    const hex = (n) => n.toString(16).padStart(2, "0").toUpperCase();
    return `Color(0x${hex(Math.round(a * 255))}${hex(r)}${hex(g)}${hex(b)})`;
  };
  const colors = tokens.filter((t) => t.type === "color");
  const fields = colors.map((t) => `    val ${camel(t.path.slice(1))}: Color,`);
  const inst = (pick) => colors.map((t) => `    ${camel(t.path.slice(1))} = ${argb(pick(t))},`).join("\n");
  const dims = (group) =>
    tokens
      .filter((t) => t.path[0] === group && /^[\d.]+(px)?$/.test(String(t.value)))
      .map((t) => `        val ${camel(t.path.slice(1))} = ${px(t.value)}.dp`);
  const phoneType = tokens
    .filter((t) => t.path[0] === "type" && t.path[1] === "phone")
    .map((t) => {
      const v = t.value;
      const fam = v.fontFamily === "{font.paper}" ? "TypeFamily.Paper" : "TypeFamily.App";
      return `        val ${camel(t.path.slice(2))} = TypeRole(${fam}, ${px(v.fontSize)}.sp, FontWeight(${v.fontWeight}), ${v.lineHeight ?? 1.2}f)`;
    });
  const motion = tokens
    .filter((t) => t.path[0] === "motion" && t.type === "duration")
    .map((t) => `        const val ${camel(t.path.slice(1))} = ${px(t.value)}`);
  return `// ${HEADER}
package com.mytaillog.design

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.TextUnit
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

@Immutable
data class MyTailLogColors(
${fields.join("\n")}
)

val LightColors = MyTailLogColors(
${inst((t) => t.value)}
)

val DarkColors = MyTailLogColors(
${inst((t) => t.dark ?? t.value)}
)

enum class TypeFamily { App, Paper }

data class TypeRole(val family: TypeFamily, val size: TextUnit, val weight: FontWeight, val lineHeight: Float)

object Tokens {
    object Space {
${dims("space").join("\n")}
    }
    object Radius {
${dims("radius").join("\n")}
    }
    object Size {
${dims("size").join("\n")}
    }
    object Map {
${dims("map").join("\n")}
    }
    object PhoneType {
${phoneType.join("\n")}
    }
    object MotionMs {
${motion.join("\n")}
    }
}
`;
}

export function build(json) {
  const tokens = flatten(json);
  return { css: buildCss(tokens), swift: buildSwift(tokens), kotlin: buildKotlin(tokens) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = build(JSON.parse(readFileSync(SRC, "utf8")));
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [k, file] of Object.entries(OUT)) {
    if (check) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== out[k]) {
        console.error(`stale: ${file}`);
        stale++;
      }
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, out[k]);
      console.log(`wrote ${file.slice(ROOT.length + 1)}`);
    }
  }
  if (stale) {
    console.error("Run: node packages/shared/scripts/build-tokens.mjs");
    process.exit(1);
  }
}
